def main():
    rows = [l.split("|") for l in SRC.read_text(encoding="utf-8").splitlines() if l.strip()]
    names = [r[2] for r in rows]
    missing = [n for n in names if n not in MAP]
    extra = [n for n in MAP if n not in names]
    if missing or extra:
        sys.exit("ERROR: 対応が欠けている %s / 本家に無い %s" % (missing, extra))
    by = {k: [] for k in STYLES}
    dropped = []
    for code, mark, name, eff, axis, n in rows:
        m = MAP[name]
        if m.startswith("x:"):
            dropped.append((name, m[2:]))
        else:
            by[m].append(name)
    empty = [k for k, v in by.items() if not v]
    out = ["| 本作のスタイル | 範囲 | 軸 | 吸収した本家の戦術 | 数 |", "|---|---|---|---|---|"]
    for k, (nm, scope, axis) in STYLES.items():
        src = by[k]
        out.append("| %s %s | %s | %s | %s | %d |" % (k, nm, scope, axis, " / ".join(src) if src else "(本作で追加)", len(src)))
    out.append("")
    out.append("除外: " + " / ".join("%s(%s)" % d for d in dropped))
    out.append("")
    out.append("本家 %d種 → 本作 %d種(全体 %d / 個人 %d)。吸収元の無いスタイル: %s" % (
        len(rows), len(STYLES), sum(1 for v in STYLES.values() if v[1] == "全体"),
        sum(1 for v in STYLES.values() if v[1] == "個人"), " / ".join(STYLES[k][0] for k in empty) or "なし"))
    doc = DOC.read_text(encoding="utf-8")
    i, j = doc.index(BEGIN) + len(BEGIN), doc.index(END)
    DOC.write_text(doc[:i] + "\n" + "\n".join(out) + "\n" + doc[j:], encoding="utf-8", newline="\n")
    sys.stdout.buffer.write(("\n".join(out[-3:]) + "\n").encode("utf-8"))


if __name__ == "__main__":
    main()
